-- Task feedback: the owner or the assignee of a weekly task attaches a file
-- (image or document) as feedback. feedback_user_id and created_by both record
-- the sender; is_task_owner is true when the sender owns the task and false
-- when they are the assignee. The trigger enforces who may send and sets the
-- flag; rows are immutable (no update policy). Files live in the private
-- 'task-feedback' bucket under <auth uid>/<unique>.<ext>.
create table public.task_feedback (
  id bigint generated by default as identity primary key,
  feedback_user_id uuid not null references public.profiles(id),
  task_id bigint not null references public.weekly_plans(id) on delete cascade,
  is_task_owner boolean not null default false,
  file_path text not null,
  created_at timestamptz not null default now(),
  created_by uuid not null references public.profiles(id)
);

create index task_feedback_task_id_idx on public.task_feedback (task_id);

create or replace function public.enforce_task_feedback_insert()
returns trigger
language plpgsql
as $$
declare
  actor uuid := auth.uid();
  task_owner uuid;
  task_assignee uuid;
begin
  select created_by, assigned_personnel
    into task_owner, task_assignee
    from public.weekly_plans
   where id = new.task_id;

  if not found then
    raise exception 'Task not found.';
  end if;

  if actor = task_owner then
    new.is_task_owner := true;
  elsif actor = task_assignee then
    new.is_task_owner := false;
  else
    raise exception 'Only the task owner or the assigned person may add feedback.';
  end if;

  if new.file_path not like actor::text || '/%' then
    raise exception 'Feedback files must be uploaded to your own folder.';
  end if;

  new.feedback_user_id := actor;
  new.created_by := actor;
  return new;
end;
$$;

create trigger task_feedback_before_insert
  before insert on public.task_feedback
  for each row execute function public.enforce_task_feedback_insert();

alter table public.task_feedback enable row level security;

create policy "task_feedback_select_parties_admin"
  on public.task_feedback
  for select
  to authenticated
  using (
    created_by = auth.uid()
    or feedback_user_id = auth.uid()
    or public.is_super_admin()
    or exists (
      select 1
      from public.weekly_plans p
      where p.id = task_id
        and (p.created_by = auth.uid() or p.assigned_personnel = auth.uid())
    )
  );

create policy "task_feedback_insert_own"
  on public.task_feedback
  for insert
  to authenticated
  with check (created_by = auth.uid());

create policy "task_feedback_delete_own_admin"
  on public.task_feedback
  for delete
  to authenticated
  using (created_by = auth.uid() or public.is_super_admin());

grant select, insert, delete on public.task_feedback to authenticated;
grant usage, select on sequence public.task_feedback_id_seq to authenticated;

insert into storage.buckets (id, name, public, file_size_limit)
values ('task-feedback', 'task-feedback', false, 20971520)
on conflict (id) do nothing;

drop policy if exists "task_feedback_files_read" on storage.objects;
create policy "task_feedback_files_read"
on storage.objects
for select
to authenticated
using (
  bucket_id = 'task-feedback'
  and exists (
    select 1
    from public.task_feedback f
    where f.file_path = name
  )
);

drop policy if exists "task_feedback_files_insert_own" on storage.objects;
create policy "task_feedback_files_insert_own"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'task-feedback'
  and (storage.foldername(name))[1] = auth.uid()::text
);

drop policy if exists "task_feedback_files_update_own" on storage.objects;
create policy "task_feedback_files_update_own"
on storage.objects
for update
to authenticated
using (
  bucket_id = 'task-feedback'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_super_admin()
  )
)
with check (
  bucket_id = 'task-feedback'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_super_admin()
  )
);

drop policy if exists "task_feedback_files_delete_own" on storage.objects;
create policy "task_feedback_files_delete_own"
on storage.objects
for delete
to authenticated
using (
  bucket_id = 'task-feedback'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_super_admin()
  )
);

