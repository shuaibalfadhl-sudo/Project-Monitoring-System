-- Weekly plans: any authenticated user creates their own plans and assigns a
-- person; the assignee may only move an in progress task to done; owners and
-- super admins can change anything; super admins see and delete everything.
-- Timestamps are TIMESTAMPTZ written with now(), which Postgres stores in UTC.

-- Role helper used by the RLS policies below and by storage policies.
create or replace function public.is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'super_admin'
  );
$$;

revoke all on function public.is_super_admin() from public;
grant execute on function public.is_super_admin() to authenticated;

create table public.weekly_plans (
  id bigint generated by default as identity primary key,
  assigned_personnel uuid not null references public.profiles(id),
  module text not null,
  date_weekly date,
  title text not null,
  description text,
  status text not null default 'pending',
  document_attachments text[],
  created_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_by uuid references public.profiles(id),
  updated_at timestamptz,
  constraint weekly_plans_status_check
    check (status in ('pending', 'onhold', 'in progress', 'done', 'completed'))
);

create index weekly_plans_assigned_personnel_idx
  on public.weekly_plans (assigned_personnel);
create index weekly_plans_created_by_idx
  on public.weekly_plans (created_by);

-- Enforces the status transition rules and fills updated_by / updated_at.
-- RLS decides who may attempt an update; this trigger decides what may change.
create or replace function public.enforce_weekly_plan_update()
returns trigger
language plpgsql
as $$
declare
  actor uuid := auth.uid();
begin
  if actor = old.created_by or public.is_super_admin() then
    new.updated_by := actor;
    new.updated_at := now();
    return new;
  end if;

  if actor = old.assigned_personnel
     and old.status = 'in progress'
     and new.status = 'done'
     and new.assigned_personnel = old.assigned_personnel
     and new.module is not distinct from old.module
     and new.date_weekly is not distinct from old.date_weekly
     and new.title is not distinct from old.title
     and new.description is not distinct from old.description
     and new.document_attachments is not distinct from old.document_attachments
     and new.created_by = old.created_by
     and new.created_at = old.created_at
  then
    new.updated_by := actor;
    new.updated_at := now();
    return new;
  end if;

  raise exception 'Assigned personnel may only change an in progress task to done.';
end;
$$;

create trigger weekly_plans_before_update
  before update on public.weekly_plans
  for each row execute function public.enforce_weekly_plan_update();

alter table public.weekly_plans enable row level security;

create policy "weekly_plans_select_creator_assignee_admin"
  on public.weekly_plans
  for select
  to authenticated
  using (
    created_by = auth.uid()
    or assigned_personnel = auth.uid()
    or public.is_super_admin()
  );

create policy "weekly_plans_insert_own"
  on public.weekly_plans
  for insert
  to authenticated
  with check (created_by = auth.uid());

create policy "weekly_plans_update_creator_assignee_admin"
  on public.weekly_plans
  for update
  to authenticated
  using (
    created_by = auth.uid()
    or assigned_personnel = auth.uid()
    or public.is_super_admin()
  )
  with check (
    created_by = auth.uid()
    or assigned_personnel = auth.uid()
    or public.is_super_admin()
  );

create policy "weekly_plans_delete_creator_admin"
  on public.weekly_plans
  for delete
  to authenticated
  using (created_by = auth.uid() or public.is_super_admin());

grant select, insert, update, delete on public.weekly_plans to authenticated;
grant usage, select on sequence public.weekly_plans_id_seq to authenticated;

-- Private bucket for attachments. Object layout: <auth uid>/<unique>.<ext>
insert into storage.buckets (id, name, public, file_size_limit)
values ('weekly-plan-documents', 'weekly-plan-documents', false, 20971520)
on conflict (id) do nothing;

drop policy if exists "weekly_plan_documents_read" on storage.objects;
create policy "weekly_plan_documents_read"
on storage.objects
for select
to authenticated
using (bucket_id = 'weekly-plan-documents');

drop policy if exists "weekly_plan_documents_insert_own" on storage.objects;
create policy "weekly_plan_documents_insert_own"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'weekly-plan-documents'
  and (storage.foldername(name))[1] = auth.uid()::text
);

drop policy if exists "weekly_plan_documents_update_own" on storage.objects;
create policy "weekly_plan_documents_update_own"
on storage.objects
for update
to authenticated
using (
  bucket_id = 'weekly-plan-documents'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_super_admin()
  )
)
with check (
  bucket_id = 'weekly-plan-documents'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_super_admin()
  )
);

drop policy if exists "weekly_plan_documents_delete_own" on storage.objects;
create policy "weekly_plan_documents_delete_own"
on storage.objects
for delete
to authenticated
using (
  bucket_id = 'weekly-plan-documents'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_super_admin()
  )
);
