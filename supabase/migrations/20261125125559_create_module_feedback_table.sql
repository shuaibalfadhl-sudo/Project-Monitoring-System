-- Module feedback: users (QA auditors, project managers, developers) provide feedback
-- on modules. Each feedback entry records the user, their role, and optional files.
-- Feedback is attached to a specific module and is immutable after creation.
-- Files live in the private 'module-feedback' bucket under <auth uid>/<unique>.<ext>.

create table if not exists public.module_feedback (
  id bigint generated by default as identity primary key,
  feedback_user_id uuid not null references public.profiles(id),
  module_id uuid not null references public.project_modules(id) on delete cascade,
  user_role text not null,
  feedback text,
  file_paths text[] not null default '{}',
  created_at timestamptz not null default now(),
  created_by uuid not null references public.profiles(id)
);

create index if not exists module_feedback_module_id_idx on public.module_feedback (module_id);
create index if not exists module_feedback_created_by_idx on public.module_feedback (created_by);

-- Enforce who may insert and validate file paths
create or replace function public.enforce_module_feedback_insert()
returns trigger
language plpgsql
as $$
declare
  actor uuid := auth.uid();
  module_record record;
  valid_role boolean;
begin
  select assigned_developer_id, qa_acknowledged_by, project_id
    into module_record
    from public.project_modules
   where id = new.module_id;

  if not found then
    raise exception 'Module not found.';
  end if;

  -- Validate that the user's role matches the module's stakeholders
  -- Roles allowed: assigned developer, QA auditor, project members
  valid_role := (
    public.is_super_admin()
    or actor = module_record.assigned_developer_id
    or actor = module_record.qa_acknowledged_by
    or exists (
      select 1
      from public.project_members pm
      join public.projects p on p.id = pm.project_id
      where p.id = module_record.project_id
        and pm.user_id = actor
    )
  );

  if not valid_role then
    raise exception 'Only assigned developers, QA auditors, or project members may add feedback.';
  end if;

  -- Validate file paths belong to the actor
  if exists (
    select 1
    from unnest(new.file_paths) as p
    where p not like actor::text || '/%'
  ) then
    raise exception 'Feedback files must be uploaded to your own folder.';
  end if;

  new.feedback_user_id := actor;
  new.created_by := actor;
  return new;
end;
$$;

drop trigger if exists module_feedback_before_insert on public.module_feedback;
create trigger module_feedback_before_insert
  before insert on public.module_feedback
  for each row execute function public.enforce_module_feedback_insert();

alter table public.module_feedback enable row level security;

-- Select: feedback providers, module stakeholders, and admins
drop policy if exists "module_feedback_select_parties_admin" on public.module_feedback;
create policy "module_feedback_select_parties_admin"
  on public.module_feedback
  for select
  to authenticated
  using (
    created_by = auth.uid()
    or feedback_user_id = auth.uid()
    or public.is_super_admin()
    or exists (
      select 1
      from public.project_modules m
      where m.id = module_id
        and (
          m.assigned_developer_id = auth.uid()
          or m.qa_acknowledged_by = auth.uid()
          or exists (
            select 1
            from public.project_members pm
            where pm.project_id = m.project_id
              and pm.user_id = auth.uid()
          )
        )
    )
  );

-- Insert: only the creator
drop policy if exists "module_feedback_insert_own" on public.module_feedback;
create policy "module_feedback_insert_own"
  on public.module_feedback
  for insert
  to authenticated
  with check (created_by = auth.uid());

-- Delete: creator or admin
drop policy if exists "module_feedback_delete_own_admin" on public.module_feedback;
create policy "module_feedback_delete_own_admin"
  on public.module_feedback
  for delete
  to authenticated
  using (created_by = auth.uid() or public.is_super_admin());

grant select, insert, delete on public.module_feedback to authenticated;
grant usage, select on sequence public.module_feedback_id_seq to authenticated;

-- Storage bucket for feedback files
insert into storage.buckets (id, name, public, file_size_limit)
values ('module-feedback', 'module-feedback', false, 20971520)
on conflict (id) do nothing;

-- Storage policies
drop policy if exists "module_feedback_files_read" on storage.objects;
create policy "module_feedback_files_read"
on storage.objects
for select
to authenticated
using (
  bucket_id = 'module-feedback'
  and exists (
    select 1
    from public.module_feedback f
    where name = any(f.file_paths)
  )
);

drop policy if exists "module_feedback_files_insert_own" on storage.objects;
create policy "module_feedback_files_insert_own"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'module-feedback'
  and (storage.foldername(name))[1] = auth.uid()::text
);

drop policy if exists "module_feedback_files_update_own" on storage.objects;
create policy "module_feedback_files_update_own"
on storage.objects
for update
to authenticated
using (
  bucket_id = 'module-feedback'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_super_admin()
  )
)
with check (
  bucket_id = 'module-feedback'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_super_admin()
  )
);

drop policy if exists "module_feedback_files_delete_own" on storage.objects;
create policy "module_feedback_files_delete_own"
on storage.objects
for delete
to authenticated
using (
  bucket_id = 'module-feedback'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_super_admin()
  )
);
